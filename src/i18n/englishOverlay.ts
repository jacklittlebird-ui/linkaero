const ARABIC = /[\u0600-\u06FF]/;
const DICT = PAIRS.sort((a, b) => b[0].length - a[0].length).map(
  ([ar, en]) => [new RegExp(ar.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "g"), en] as [RegExp, string],
);

export function toEnglish(text: string): string {
  if (!ARABIC.test(text)) return text;
  let out = text;
  for (const [re, en] of DICT) {
    out = out.replace(re, en);
    if (!ARABIC.test(out)) break;
  }
  return out;
}
